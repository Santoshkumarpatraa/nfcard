export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 20,
  strokeWidth = 1.75,
  ...props
}: { name: IconName; size?: number; strokeWidth?: number } & Omit<SVGProps<SVGSVGElement>, "name">) {
  const shapes: Shape[] = ICONS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {shapes.map((shape, index) => {
        if ("d" in shape) return <path key={index} d={shape.d} />;
        if ("circle" in shape) {
          const [cx, cy, r] = shape.circle;
          return <circle key={index} cx={cx} cy={cy} r={r} />;
        }
        if ("rect" in shape) {
          const [x, y, width, height, rx] = shape.rect;
          return <rect key={index} x={x} y={y} width={width} height={height} rx={rx} />;
        }
        return <polygon key={index} points={shape.polygon} />;
      })}
    </svg>
  );
}
